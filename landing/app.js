let language = localStorage.getItem("worldmodel-site-language") || "zh";
if (!copy[language]) language = "zh";
let release = { version: "v1.0.0", assets: {}, notarized: false };
const platform = document.querySelector("#platform");
platform.value = /Win/i.test(navigator.platform)
  ? "windows"
  : /Linux/i.test(navigator.platform)
    ? "deb"
    : "mac-arm64";
function updateDownloads() {
  document.querySelector("#version").textContent = release.version;
  document.querySelectorAll("[data-package]").forEach((link) => {
    link.href =
      release.assets[link.dataset.package] ||
      "https://github.com/bennix/WorldAIVideo/releases/latest";
  });
  document.querySelector("#primary-download").href =
    release.assets[platform.value] ||
    "https://github.com/bennix/WorldAIVideo/releases/latest";
  document.querySelectorAll("[data-mac-status]").forEach((label) => {
    label.textContent =
      copy[language][release.notarized ? "notarized" : "macPackage"];
  });
}
function translate(value) {
  language = value;
  localStorage.setItem("worldmodel-site-language", value);
  document.documentElement.lang = value === "zh" ? "zh-CN" : value;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = copy[value][element.dataset.i18n];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    element.innerHTML = copy[value][element.dataset.i18nHtml];
  });
  document.querySelector("#language").value = value;
  document
    .querySelector("#play-demo")
    .setAttribute("aria-label", copy[value].playDemo);
  updateDownloads();
}
document
  .querySelector("#language")
  .addEventListener("change", (event) => translate(event.target.value));
platform.addEventListener("change", updateDownloads);
const video = document.querySelector("#demo"),
  playButton = document.querySelector("#play-demo");
playButton.addEventListener("click", async () => {
  try {
    video.controls = true;
    await video.play();
    playButton.hidden = true;
    video.closest("figure").classList.add("playing");
  } catch {
    video.controls = true;
  }
});
translate(language);
fetch("release.json")
  .then((response) => {
    if (!response.ok) throw new Error("Release metadata unavailable");
    return response.json();
  })
  .then((data) => {
    release = data;
    updateDownloads();
  })
  .catch(() => {});
